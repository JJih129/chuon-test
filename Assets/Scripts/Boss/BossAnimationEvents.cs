        {
            Debug.LogError("BossAnimationEvents: ????/???? ??????????? BossController ????????? ??? ?? ???????.");
            enabled = false;
        }
    }

    // === ??????? ???? ??? (Unity Animator???? ???) ===

    public void SignalPatternEnd()
    {
        if (bossController != null)
        {
            bossController.OnAnimationPatternEnd();
        }
    }

    /// <summary>
    /// ??????? ????? ???? ???? ???? ?????? ???????.
    /// </summary>
    public void ActivateHitbox()
    {
        if (bossController != null)
